"""Check crossl1/data/inventories.yaml against PHOIBLE, and test whether any
disagreement would change Study 2's predictors.

PHOIBLE (Moran & McCloy 2019) holds several independently sourced inventories per
language. For each L1 this script:
  1. lists consonants in our inventory that PHOIBLE sources lack, and the reverse;
  2. re-runs the automatic projection of the 24 English consonants with each PHOIBLE
     inventory and reports which English consonants would map differently.

This is a sensitivity check. It does NOT change inventories.yaml: the cross-L1 analysis
was frozen (commit 5f99ff1) before it was run.

Usage:
    curl -o phoible.csv https://raw.githubusercontent.com/phoible/dev/5f82b9c3fbb0b5c630de20e254c5fdad645e3e56/data/phoible.csv
    python crossl1/code/check_inventories_phoible.py phoible.csv > crossl1/INVENTORY_CHECK.md
"""
from __future__ import annotations

import csv
import hashlib
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from phonosim.features import normalize_ipa  # noqa: E402
from phonosim.l1.project import load_inventory, project  # noqa: E402

INV = ROOT / "crossl1" / "data" / "inventories.yaml"
ENGLISH = ["p", "b", "t", "d", "k", "ɡ", "f", "v", "θ", "ð", "s", "z", "ʃ", "ʒ", "h",
           "t͡ʃ", "d͡ʒ", "m", "n", "ŋ", "l", "ɹ", "w", "j"]
L1_ISO = {"hindi": ["hin"], "arabic": ["arb", "arz"], "mandarin": ["cmn"],
          "korean": ["kor"], "spanish": ["spa"], "vietnamese": ["vie"]}

# PHOIBLE spelling -> the spelling our inventories use
_SUBS = [("ʱ", "\u0324"), ("g", "ɡ"), ("ʦ", "t͡s"), ("ʧ", "t͡ʃ"), ("ʤ", "d͡ʒ")]
_DROP = {"\u0320", "ː", "\u031A", "\u0348"}  # retraction, length, unreleased, fortis
# Place-detail marks that are a transcription convention, not a category difference:
# dental, laminal, apical, retracted tongue root (used on Arabic emphatics).
_NOTATION = {"\u032A", "\u033B", "\u033A", "\u0319"}
_AFFRICATES = ["tʃ", "dʒ", "ts", "dz", "tɕ", "dʑ", "ʈʂ", "ɖʐ", "cç", "ɟʝ"]


def clean(seg: str) -> str:
    """PHOIBLE symbol -> PanPhon-parseable symbol with the same category."""
    s = unicodedata.normalize("NFD", seg.split("|")[-1])  # UPSID 't̪|t': place unspecified
    for a, b in _SUBS:
        s = s.replace(a, b)
    s = "".join(ch for ch in s if ch not in _DROP).replace("\u0361", "")
    breathy = "\u0324" in s and len(s.replace("\u0324", "")) == 2
    if breathy:  # d̤ʒ̤ -> d͡ʒ̤
        s = s.replace("\u0324", "") + "\u0324"
    for aff in _AFFRICATES:
        s = s.replace(aff, aff[0] + "\u0361" + aff[1:])
    return unicodedata.normalize("NFC", s)


def canon(seg: str) -> str:
    """Comparison key: clean() plus dropping place-detail notation."""
    s = unicodedata.normalize("NFD", clean(seg))
    return unicodedata.normalize("NFC", "".join(ch for ch in s if ch not in _NOTATION))


def phoible_inventories(path: str):
    invs = defaultdict(lambda: {"cons": set(), "marginal": set(), "meta": None})
    with open(path, encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if r["SegmentClass"] != "consonant":
                continue
            key = (r["ISO6393"], r["InventoryID"])
            inv = invs[key]
            inv["meta"] = f'{r["Source"]} #{r["InventoryID"]} {r["LanguageName"]}' + (
                f' ({r["SpecificDialect"]})' if r["SpecificDialect"] not in ("", "NA") else "")
            target = inv["marginal"] if r["Marginal"] == "TRUE" else inv["cons"]
            target.add(clean(r["Phoneme"]))
    return invs


def parseable(segs):
    ok, bad = [], []
    for s in segs:
        try:
            n = normalize_ipa(s)
            if n not in ok:
                ok.append(n)
        except (ValueError, KeyError, IndexError):
            bad.append(s)
    return ok, bad


def main(phoible_path: str):
    invs = phoible_inventories(phoible_path)
    print("# Inventory check against PHOIBLE\n")
    print("Generated by `crossl1/code/check_inventories_phoible.py`. Sensitivity check only;")
    print("`inventories.yaml` is frozen and unchanged.\n")
    sha = hashlib.sha256(Path(phoible_path).read_bytes()).hexdigest()[:16]
    print(f"PHOIBLE data: phoible/dev commit 5f82b9c (Nov 2026), phoible.csv sha256 {sha}...\n")
    print("Symbols are compared after removing pure notation: length, retraction, fortis and")
    print("dental/laminal/apical marks, and UPSID's 't̪|t' (place unspecified). So PHOIBLE's")
    print("t̠ʃ counts as our t͡ʃ and n̪ as our n. What is left are category differences.")
    print("Marginal phonemes are listed but not counted.\n")
    summary = []
    for l1, isos in L1_ISO.items():
        ours = set(canon(s) for s in load_inventory(l1, INV))
        our_proj = {e: project(e, load_inventory(l1, INV)) for e in ENGLISH}
        print(f"## {l1.capitalize()}\n")
        print(f"Ours ({len(ours)}): {' '.join(sorted(load_inventory(l1, INV)))}\n")
        print("| PHOIBLE source | n | In PHOIBLE, not ours | In ours, not PHOIBLE | Marginal | English consonants that would project differently |")
        print("|---|---|---|---|---|---|")
        n_changed = []
        for (iso, iid), inv in sorted(invs.items()):
            if iso not in isos:
                continue
            usable, bad = parseable(sorted(inv["cons"]))
            theirs = {canon(x) for x in inv["cons"]}
            changed = []
            if usable:
                for e in ENGLISH:
                    p = project(e, tuple(usable))
                    if {canon(x) for x in p} != {canon(x) for x in our_proj[e]}:
                        changed.append(f"{e}: {'/'.join(our_proj[e])}→{'/'.join(p)}")
            n_changed.append(len(changed))
            extra_note = f" (unparseable: {' '.join(bad)})" if bad else ""
            print(f"| {inv['meta']} | {len(theirs)} | {' '.join(sorted(theirs - ours)) or '-'}{extra_note} "
                  f"| {' '.join(sorted(ours - theirs)) or '-'} | {' '.join(sorted(canon(x) for x in inv['marginal'])) or '-'} "
                  f"| {'; '.join(changed) or 'none'} |")
        summary.append((l1, n_changed))
        print()
    print("## Summary\n")
    print("| L1 | PHOIBLE sources | English consonants changed per source |")
    print("|---|---|---|")
    for l1, n in summary:
        print(f"| {l1} | {len(n)} | {', '.join(map(str, n))} |")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "phoible.csv")
